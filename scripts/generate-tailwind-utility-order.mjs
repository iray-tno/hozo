// A bounded builtin utility domain. Ask Tailwind for property-sort metadata;
// do not infer shorthand/axis/side precedence from authored class order.
import assert from 'node:assert/strict'
import { readFileSync, writeFileSync } from 'node:fs'
import { __unstable__loadDesignSystem } from 'tailwindcss'

const design = await __unstable__loadDesignSystem('@theme { --spacing: .25rem; }')
const roots = [
  'p',
  'px',
  'py',
  'pt',
  'pr',
  'pb',
  'pl',
  'm',
  'mx',
  'my',
  'mt',
  'mr',
  'mb',
  'ml',
  'gap',
  'gap-x',
  'gap-y',
]
const entries = roots
  .map((root) => {
    const compiled = design.compileAstNodes(design.parseCandidate(`${root}-4`)[0])
    assert.equal(compiled.length, 1)
    const { order, count } = compiled[0].propertySort
    // Every value of these roots has this single-property signature.
    assert.equal(order.length, 1)
    assert.equal(count, 1)
    return { root, key: order[0] }
  })
  .sort((a, b) => a.root.localeCompare(b.root))
const source = `// Generated by scripts/generate-tailwind-utility-order.mjs. Do not edit.
// Tailwind builtin physical spacing utilities; logical/physical aliasing is not modeled.
pub const SPACING_ORDER: &[(&str, u16)] = &[
${entries.map(({ root, key }) => `    (${JSON.stringify(root)}, ${key}),`).join('\n')}
];
`
const target = new URL('../crates/hozo_parser/src/tailwind_utility_order.rs', import.meta.url)
if (process.argv.includes('--check')) assert.equal(readFileSync(target, 'utf8'), source)
else writeFileSync(target, source)
