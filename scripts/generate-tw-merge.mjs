// Generates `crates/hozo_parser/src/tw_merge_table.rs` from `tailwind-merge`.
//
// `getDefaultConfig()` in `tailwind-merge` defines the class-group trie,
// validator predicates, conflict tables, and order-sensitive modifiers that
// `twMerge` uses at runtime. Generating the static trie directly from the
// installed `tailwind-merge` package keeps the table tied to its reference
// implementation. The entry digests let the bundler prove it resolved that
// same implementation before eliminating a merger call.
//
//   node scripts/generate-tw-merge.mjs
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'

const require = createRequire(
  new URL('../packages/tailwind-conformance/package.json', import.meta.url),
)
const { getDefaultConfig, validators } = require('tailwind-merge')
const packageRoot = path.dirname(path.dirname(require.resolve('tailwind-merge')))
const manifest = JSON.parse(readFileSync(path.join(packageRoot, 'package.json'), 'utf8'))
const entry = manifest.exports['.']
const digest = (file) =>
  createHash('sha256')
    .update(readFileSync(path.join(packageRoot, file)))
    .digest('hex')
const entryDigests = [...new Set([entry.import, entry.require, entry.default])].map(digest)
const configId = `${manifest.version}:${entryDigests[0]}`

const config = getDefaultConfig()
const validatorNames = new Map(Object.entries(validators).map(([name, fn]) => [fn, name]))

function createNode() {
  return {
    nextPart: new Map(),
    validators: [],
    classGroupId: null,
  }
}

function getPart(node, path) {
  let current = node
  for (const part of path.split('-')) {
    let next = current.nextPart.get(part)
    if (!next) {
      next = createNode()
      current.nextPart.set(part, next)
    }
    current = next
  }
  return current
}

function processClasses(group, node, classGroupId, theme) {
  for (const def of group) {
    if (typeof def === 'string') {
      const target = def === '' ? node : getPart(node, def)
      target.classGroupId = classGroupId
    } else if (typeof def === 'function') {
      if (def.isThemeGetter) {
        processClasses(def(theme) || [], node, classGroupId, theme)
      } else {
        const name = validatorNames.get(def)
        if (!name) {
          throw new Error(`Unknown validator function in group ${classGroupId}`)
        }
        node.validators.push({ classGroupId, validator: name })
      }
    } else if (def && typeof def === 'object') {
      for (const [key, value] of Object.entries(def)) {
        processClasses(value, getPart(node, key), classGroupId, theme)
      }
    }
  }
}

const root = createNode()
for (const [classGroupId, group] of Object.entries(config.classGroups)) {
  processClasses(group, root, classGroupId, config.theme)
}

// Flatten trie into an array of nodes in post-order so children can be
// referenced by slice/index or static references.
const nodes = []
function flatten(node) {
  const children = []
  const sortedKeys = [...node.nextPart.keys()].sort()
  for (const key of sortedKeys) {
    const childIdx = flatten(node.nextPart.get(key))
    children.push([key, childIdx])
  }
  const idx = nodes.length
  nodes.push({
    children,
    validators: node.validators,
    classGroupId: node.classGroupId,
  })
  return idx
}

const rootIndex = flatten(root)

const validatorVariant = {
  isAny: 'IsAny',
  isAnyNonArbitrary: 'IsAnyNonArbitrary',
  isArbitraryFamilyName: 'IsArbitraryFamilyName',
  isArbitraryImage: 'IsArbitraryImage',
  isArbitraryLength: 'IsArbitraryLength',
  isArbitraryNumber: 'IsArbitraryNumber',
  isArbitraryPosition: 'IsArbitraryPosition',
  isArbitraryShadow: 'IsArbitraryShadow',
  isArbitrarySize: 'IsArbitrarySize',
  isArbitraryValue: 'IsArbitraryValue',
  isArbitraryVariable: 'IsArbitraryVariable',
  isArbitraryVariableFamilyName: 'IsArbitraryVariableFamilyName',
  isArbitraryVariableImage: 'IsArbitraryVariableImage',
  isArbitraryVariableLength: 'IsArbitraryVariableLength',
  isArbitraryVariablePosition: 'IsArbitraryVariablePosition',
  isArbitraryVariableShadow: 'IsArbitraryVariableShadow',
  isArbitraryVariableSize: 'IsArbitraryVariableSize',
  isArbitraryVariableWeight: 'IsArbitraryVariableWeight',
  isArbitraryWeight: 'IsArbitraryWeight',
  isFraction: 'IsFraction',
  isInteger: 'IsInteger',
  isNamedContainerQuery: 'IsNamedContainerQuery',
  isNumber: 'IsNumber',
  isPercent: 'IsPercent',
  isTshirtSize: 'IsTshirtSize',
}

const conflictingEntries = Object.entries(config.conflictingClassGroups).sort(([a], [b]) =>
  a.localeCompare(b),
)
const conflictingModifierEntries = Object.entries(config.conflictingClassGroupModifiers).sort(
  ([a], [b]) => a.localeCompare(b),
)
const postfixLookup = [...(config.postfixLookupClassGroups ?? [])].sort()
const orderSensitive = [...(config.orderSensitiveModifiers ?? [])].sort()

const rust = `// Generated by scripts/generate-tw-merge.mjs from tailwind-merge. Do not edit.

pub const DEFAULT_CONFIG_ID: &str = ${JSON.stringify(configId)};

#[allow(clippy::enum_variant_names)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Validator {
    IsAny,
    IsAnyNonArbitrary,
    IsArbitraryFamilyName,
    IsArbitraryImage,
    IsArbitraryLength,
    IsArbitraryNumber,
    IsArbitraryPosition,
    IsArbitraryShadow,
    IsArbitrarySize,
    IsArbitraryValue,
    IsArbitraryVariable,
    IsArbitraryVariableFamilyName,
    IsArbitraryVariableImage,
    IsArbitraryVariableLength,
    IsArbitraryVariablePosition,
    IsArbitraryVariableShadow,
    IsArbitraryVariableSize,
    IsArbitraryVariableWeight,
    IsArbitraryWeight,
    IsFraction,
    IsInteger,
    IsNamedContainerQuery,
    IsNumber,
    IsPercent,
    IsTshirtSize,
}

pub struct TrieNode {
    pub children: &'static [(&'static str, usize)],
    pub validators: &'static [(&'static str, Validator)],
    pub class_group_id: Option<&'static str>,
}

pub const ROOT_INDEX: usize = ${rootIndex};

pub const TRIE_NODES: &[TrieNode] = &[
${nodes
  .map((n) => {
    const children = n.children.map(([k, idx]) => `(${JSON.stringify(k)}, ${idx})`).join(', ')
    const validators = n.validators
      .map(
        ({ classGroupId, validator }) =>
          `(${JSON.stringify(classGroupId)}, Validator::${validatorVariant[validator]})`,
      )
      .join(', ')
    const group = n.classGroupId === null ? 'None' : `Some(${JSON.stringify(n.classGroupId)})`
    return `    TrieNode {
        children: &[${children}],
        validators: &[${validators}],
        class_group_id: ${group},
    },`
  })
  .join('\n')}
];

pub const CONFLICTING_CLASS_GROUPS: &[(&str, &[&str])] = &[
${conflictingEntries
  .map(
    ([k, list]) =>
      `    (${JSON.stringify(k)}, &[${list.map((v) => JSON.stringify(v)).join(', ')}]),`,
  )
  .join('\n')}
];

pub const CONFLICTING_CLASS_GROUP_MODIFIERS: &[(&str, &[&str])] = &[
${conflictingModifierEntries
  .map(
    ([k, list]) =>
      `    (${JSON.stringify(k)}, &[${list.map((v) => JSON.stringify(v)).join(', ')}]),`,
  )
  .join('\n')}
];

pub const POSTFIX_LOOKUP_CLASS_GROUPS: &[&str] = &[
${postfixLookup.map((v) => `    ${JSON.stringify(v)},`).join('\n')}
];

pub const ORDER_SENSITIVE_MODIFIERS: &[&str] = &[
${orderSensitive.map((v) => `    ${JSON.stringify(v)},`).join('\n')}
];
`

writeFileSync('crates/hozo_parser/src/tw_merge_table.rs', rust)
writeFileSync(
  'packages/compiler/src/tw-merge-config.ts',
  `// Generated by scripts/generate-tw-merge.mjs. Do not edit.
export const TAILWIND_MERGE_CONFIG =
  '${configId}'
export const TAILWIND_MERGE_ENTRY_DIGESTS = [
${entryDigests.map((hash) => `  '${hash}',`).join('\n')}
]
`,
)
console.log(`wrote ${nodes.length} tw-merge trie nodes`)
