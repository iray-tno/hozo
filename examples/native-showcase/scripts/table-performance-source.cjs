const assert = require('node:assert/strict')
const { createHash } = require('node:crypto')
const { mkdirSync, readFileSync, writeFileSync } = require('node:fs')
const { resolve } = require('node:path')

// Instrument the current implementation at build time instead of maintaining
// a benchmark fork or adding diagnostics to the published component API.
function instrumentTableSource(source) {
  let output = source
  const replace = (before, after) => {
    assert.equal(output.split(before).length, 2, `Table instrumentation anchor changed: ${before}`)
    output = output.replace(before, after)
  }
  replace('  useMemo,', '  useMemo,\n  useLayoutEffect,')
  replace(
    '  const info: ColumnInfo',
    '  useLayoutEffect(() => {\n    if (!measuring) tablePerformanceProbe.resolved()\n  }, [measuring])\n\n  const info: ColumnInfo',
  )
  replace(
    '      measured.current.set(key, { column, width })',
    '      tablePerformanceProbe.measure(key)\n      measured.current.set(key, { column, width })',
  )
  replace(
    '  let column = 0\n  return ('.replaceAll('\n', source.includes('\r\n') ? '\r\n' : '\n'),
    '  useLayoutEffect(() => tablePerformanceProbe.row(), [])\n  let column = 0\n  return (',
  )
  const hash = createHash('sha256').update(source).digest('hex')
  return { hash, output }
}

function instrumentWindowedTableSource(source) {
  let output = source
  const eol = source.includes('\r\n') ? '\r\n' : '\n'
  const replace = (before, after) => {
    before = before.replaceAll('\n', eol)
    after = after.replaceAll('\n', eol)
    assert.equal(
      output.split(before).length,
      2,
      `WindowedTable instrumentation anchor changed: ${before}`,
    )
    output = output.replace(before, after)
  }
  replace("useContext } from 'react'", "useContext, useLayoutEffect } from 'react'")
  replace(
    '  const fontSize = useContext(HozoTextSizeContext)',
    '  useLayoutEffect(() => columnIndex === 0 ? tablePerformanceProbe.row(rowIndex) : undefined, [])\n  const fontSize = useContext(HozoTextSizeContext)',
  )
  replace(
    '      accessible\n      collapsable={false}',
    // biome-ignore lint/suspicious/noTemplateCurlyInString: Interpolation belongs to the generated TSX.
    '      onLayout={() => tablePerformanceProbe.cellLayout(`${rowIndex}:${columnIndex}`)}\n      accessible\n      collapsable={false}',
  )
  replace(
    '  const { width, height, keys } = useWindowedTable(props)',
    '  const { width, height, keys } = useWindowedTable(props)\n  useLayoutEffect(() => { tablePerformanceProbe.resolved() }, [])',
  )
  // Diagnostic access to the existing list, not a new public scroll API.
  replace(
    '        data={data}',
    '        ref={(list) => { tablePerformanceProbe.list = list }}\n        data={data}',
  )
  return { hash: createHash('sha256').update(source).digest('hex'), output }
}

function generateTablePerformanceSource() {
  const source = readFileSync(
    resolve(__dirname, '../../../packages/semantics/src/table.native.tsx'),
    'utf8',
  )
  const { hash, output } = instrumentTableSource(source)
  const directory = resolve(__dirname, '../src/.table-performance')
  mkdirSync(directory, { recursive: true })
  writeFileSync(
    resolve(directory, 'table.native.tsx'),
    `// Generated by table-performance-source.cjs; source SHA256 ${hash}\nimport { tablePerformanceProbe } from '../table-performance-observer'\nexport const tableSourceHash = '${hash}'\n${output}`,
  )
  const windowed = instrumentWindowedTableSource(
    readFileSync(
      resolve(__dirname, '../../../packages/patterns/src/windowed-table.native.tsx'),
      'utf8',
    ),
  )
  const model = readFileSync(
    resolve(__dirname, '../../../packages/patterns/src/windowed-table-types.ts'),
    'utf8',
  )
  const modelHash = createHash('sha256').update(model).digest('hex')
  writeFileSync(
    resolve(directory, 'windowed-table.native.tsx'),
    `// Generated by table-performance-source.cjs; source SHA256 ${windowed.hash}\nimport { tablePerformanceProbe } from '../table-performance-observer'\nexport const windowedSourceHash = '${windowed.hash}'\nexport const windowedModelHash = '${modelHash}'\n${windowed.output}`,
  )
  // Its relative import must use the same key/size validation as production.
  writeFileSync(resolve(directory, 'windowed-table-types.ts'), model)
  return hash
}

module.exports = generateTablePerformanceSource
module.exports.instrumentTableSource = instrumentTableSource
module.exports.instrumentWindowedTableSource = instrumentWindowedTableSource
if (require.main === module) generateTablePerformanceSource()
