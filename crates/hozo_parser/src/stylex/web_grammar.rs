//! The named value grammars a Web-only declaration is validated against.

/// Web-only declarations are accepted through a named value grammar rather
/// than a generic static-string escape hatch. Each newly supported property
/// therefore has an explicit validation boundary that can be tested against
/// the official StyleX transform.
#[derive(Clone, Copy)]
pub(super) enum WebValueGrammar {
    Keywords(&'static [&'static str]),
    Length {
        keywords: &'static [&'static str],
        minimum: f64,
    },
    LengthPercentage(&'static [&'static str]),
    NonNegativeLengthPercentage(&'static [&'static str]),
    LengthList {
        minimum: usize,
        maximum: usize,
    },
    SvgLength(&'static [&'static str]),
    Color,
    Integer {
        keywords: &'static [&'static str],
        minimum: i64,
        maximum: i64,
    },
    Number {
        minimum: f64,
        maximum: f64,
    },
    NumberWithKeywords {
        keywords: &'static [&'static str],
        minimum: f64,
        maximum: f64,
    },
    NumberPercentage {
        minimum: f64,
        maximum: f64,
    },
    ClipRect,
    ClipPath,
    Contain,
    ContainIntrinsicSize {
        axes: usize,
    },
    OverflowClipMargin,
    SvgDasharray,
    UrlOrNone,
    Time,
    SignedTime,
    AnimationTimingFunction,
    BorderImageOutset,
    BorderImageRepeat,
    BorderImageSlice,
    BorderImageWidth,
    GridAutoFlow,
    GridTemplateAreas,
    GridTrackList,
    CommaKeywordGroups {
        keywords: &'static [&'static str],
        minimum: usize,
        maximum: usize,
    },
    MaskImage,
    MaskPosition,
    MaskSize,
    OffsetPath,
    OffsetPosition(&'static [&'static str]),
    OffsetRotate,
    PerspectiveOrigin,
    ShapeOutside,
    WillChange,
    FontFeatureSettings,
    FontLanguageOverride,
    FontPalette,
    FontSynthesis,
    FontVariantAlternates,
    FontVariantEastAsian,
    FontVariationSettings,
    HangingPunctuation,
    HyphenateCharacter,
    HyphenateLimitChars,
    ImageResolution,
    InitialLetter,
    TimelineNames {
        allow_all: bool,
    },
    DashedIdent {
        keyword: &'static str,
    },
    AnimationTimeline,
    AnimationRangeBoundary,
    ViewTimelineInset,
    MasonryAutoFlow,
    Angle(&'static [&'static str]),
    TextDecorationSkip,
    CounterList {
        allow_reversed: bool,
    },
    ScrollbarColor,
    Quotes,
    Content,
    Zoom,
    TextDecoration,
    TextEmphasis,
    Outline,
    ViewTransitionName,
    MathDepth,
    TabSize,
    TextCombineUpright,
    TextEmphasisStyle,
    Percentage {
        keywords: &'static [&'static str],
        minimum: f64,
        maximum: f64,
    },
}
