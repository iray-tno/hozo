const quote = (value: string) => `${JSON.stringify(value)}.into()`
function rustShape(shape: OrderRuleShape): string {
  switch (shape.kind) {
    case 'rule':
      return `OrderRuleShape::Rule { selector: ${quote(shape.selector)}, nodes: ${rustNodes(shape.nodes)} }`
    case 'at-rule':
      return `OrderRuleShape::AtRule { name: ${quote(shape.name)}, params: ${quote(shape.params)}, nodes: ${rustNodes(shape.nodes)} }`
    case 'declaration':
      return `OrderRuleShape::Declaration { property: ${quote(shape.property)}, important: ${shape.important} }`
    case 'comment':
      return 'OrderRuleShape::Comment'
    case 'context':
      return `OrderRuleShape::Context { context: [${Object.entries(shape.context)
        .map(
          ([key, value]) =>
            `(${quote(key)}, crate::OrderContextValue::${typeof value === 'string' ? `String(${quote(value)})` : `Boolean(${value})`})`,
        )
        .join(',')}].into(), nodes: ${rustNodes(shape.nodes)} }`
    case 'at-root':
      return `OrderRuleShape::AtRoot { nodes: ${rustNodes(shape.nodes)} }`
  }
}
const rustNodes = (nodes: readonly OrderRuleShape[]): string =>
  `vec![${nodes.map(rustShape).join(', ')}]`

export async function generatePortableOrder() {
  const base = tailwindPackageDir()
  const version = JSON.parse(readFileSync(path.join(base, 'package.json'), 'utf8')).version
  assert.equal(version, '4.3.3', 'review the portable domain on a Tailwind upgrade')
  const css = readFileSync(path.join(base, 'theme.css'), 'utf8')
  // Plain pinned builtin CSS has no project resolver/config/module execution.
  // Use the canonical descriptor extractor, not a second ordering algorithm.
  const design = await __unstable__loadDesignSystem(css)
  const { snapshot } = describeTailwindOrder(design, portableOrderCandidates, version, [
    { file: 'builtin:tailwindcss/theme.css', sha256: orderingHash(css) },
  ])
  const candidates = snapshot.candidates.map(
    (candidate) =>
      `        OrderCandidateDescriptor { id: ${candidate.id}, candidate: ${quote(candidate.candidate)}, status: OrderCandidateStatus::${candidate.status === 'described' ? 'Described' : 'NotGenerated'}, first_rule_rank: ${candidate.firstRuleRank === null ? 'None' : `Some(${quote(candidate.firstRuleRank)})`}, rules: vec![${candidate.rules.map((rule) => `OrderRuleDescriptor { id: ${rule.id}, candidate_id: ${rule.candidateId}, variant_order: ${quote(rule.variantOrder)}, important: ${rule.important}, property_order: vec![${rule.propertyOrder.join(', ')}], declaration_count: ${rule.declarationCount}, shape: ${rustShape(rule.shape)} }`).join(', ')}] }`,
  )
  const source = `// Generated by scripts/generate-tailwind-order.mjs. Do not edit.
// Exact bounded builtin facts, not a pattern matcher, comparator or device payload.
use crate::{OrderCandidateDescriptor, OrderCandidateStatus, OrderRuleDescriptor, OrderRuleShape, OrderStylesheet, TailwindOrderSnapshot};

pub fn portable_tailwind_snapshot() -> TailwindOrderSnapshot {
    TailwindOrderSnapshot {
        schema: 1, policy: ${quote(snapshot.policy)}, tailwind_version: ${quote(version)}, fingerprint: ${quote(snapshot.fingerprint)},
        stylesheets: vec![OrderStylesheet { file: ${quote(snapshot.stylesheets[0]!.file)}, sha256: ${quote(snapshot.stylesheets[0]!.sha256)} }],
        candidates: vec![
${candidates.join(',\n')}
        ],
    }
}
`
  return { snapshot, source }
}
