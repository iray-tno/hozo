// Draws the four-way dovetail (四方蟻, shihō-ari) behind the hero and writes its
// faces to src/components/hero-joint-faces.ts:
//
//   node scripts/hero-joint.mjs
//
// scripts/og-image.mjs draws the same faces behind the Open Graph card, so
// rerun it afterwards.
//
// The joint is seen corner-on and drawn flat, one colour per piece and side.
// The two dovetails seen are the two ends of one tongue that runs straight
// across behind the near corner; the part of the lower piece between them
// holds that corner, so it is the nearest thing in the picture. The joint goes
// together by sliding level along the square's diagonal, which seen from the
// corner is straight across. It is drawn mid-way, slid by twice the tail's
// flare: the tongue's left end has gone wholly behind the near corner, so the
// left socket stands empty and the right end stands out past the lower face.
//
// Every visible region is its own polygon, so no colour lies over another and
// no anti-aliased edge of a hidden layer can show through as a hairline.
import { writeFileSync } from 'node:fs'

const LOOK = {
  upperL: '#ecd2ab',
  upperR: '#d6b48a',
  flank: '#f6e6cc',
  lowerL: '#8c653f',
  lowerR: '#5f4227',
  socket: '#2e2219',
}

// The part of a polygon on one side of the vertical line x = x0.
function sideOf(pts, x0, keepLeft) {
  const inside = (p) => (keepLeft ? x0 - p[0] : p[0] - x0) >= 0
  const out = []
  for (let i = 0; i < pts.length; i++) {
    const P = pts[i]
    const Q = pts[(i + 1) % pts.length]
    if (inside(P)) out.push(P)
    if (inside(P) !== inside(Q))
      out.push([x0, P[1] + ((Q[1] - P[1]) * (x0 - P[0])) / (Q[0] - P[0])])
  }
  return out.length >= 3 ? out : null
}

// Regions in the joint's own units: the joint line at y = 0, the seated near
// corner at x = 0. Each timber is 2·half wide and runs `reach` from the joint.
function regions({ a = 1.5, b = 2.7, t = 7, half = 10, reach = 40 } = {}) {
  const h = b // each piece has moved b, so the pair has slid 2b
  const cl = -5.5 // the tongue's left end, on the left face
  const cr = 5.5 // and its right end, on the right face
  const W = half
  const lo = (x) => x - h
  const up = (x) => x + h
  const split = (pts, x0, left, right) => [
    [sideOf(pts, x0, true), left],
    [sideOf(pts, x0, false), right],
  ]
  return [
    // The upper piece: its block, then the tongue's front face and its right end.
    ...split(
      [
        [up(-W), -reach],
        [up(W), -reach],
        [up(W), 0],
        [up(-W), 0],
      ],
      up(0),
      LOOK.upperL,
      LOOK.upperR,
    ),
    [
      [
        [up(cl + a), 0],
        [up(cr - a), 0],
        [up(cr - b), t],
        [up(cl + b), t],
      ],
      LOOK.flank,
    ],
    [
      [
        [up(cr - a), 0],
        [up(cr + a), 0],
        [up(cr + b), t],
        [up(cr - b), t],
      ],
      LOOK.upperR,
    ],
    // The lower piece left of the empty socket, the socket, and the near corner between the sockets.
    [
      [
        [lo(-W), 0],
        [lo(cl - a), 0],
        [lo(cl - b), t],
        [lo(-W), t],
      ],
      LOOK.lowerL,
    ],
    [
      [
        [lo(cl - a), 0],
        [lo(cl + a), 0],
        [lo(cl + b), t],
        [lo(cl - b), t],
      ],
      LOOK.socket,
    ],
    ...split(
      [
        [lo(cl + a), 0],
        [lo(cr - a), 0],
        [lo(cr - b), t],
        [lo(cl + b), t],
      ],
      lo(0),
      LOOK.lowerL,
      LOOK.lowerR,
    ),
    // Below the sockets, the lower block's full width.
    ...split(
      [
        [lo(-W), t],
        [lo(W), t],
        [lo(W), reach],
        [lo(-W), reach],
      ],
      lo(0),
      LOOK.lowerL,
      LOOK.lowerR,
    ),
  ].filter(([pts]) => pts)
}

// Turned 45° so the slide runs up to the right, centred on the joint, in a 100-unit square.
const SIZE = 100
const SCALE = 2.6
const TURN = (-45 * Math.PI) / 180
const place = ([x, y]) => {
  const u = x * SCALE
  const v = (y - 3.5) * SCALE
  return [
    SIZE / 2 + u * Math.cos(TURN) - v * Math.sin(TURN),
    SIZE / 2 + u * Math.sin(TURN) + v * Math.cos(TURN),
  ]
}
const f = (n) => +n.toFixed(2)
const faces = regions().map(([pts, fill]) => ({
  d: `M${pts
    .map(place)
    .map(([x, y]) => `${f(x)} ${f(y)}`)
    .join('L')}Z`,
  fill,
}))

const ts = `// Generated by scripts/hero-joint.mjs; run it rather than editing this file.
// The four-way dovetail behind the hero, in a ${SIZE}-unit square, back to front.
export const HERO_JOINT_SIZE = ${SIZE}
export const HERO_JOINT_FACES: readonly { d: string; fill: string }[] = [
${faces.map((s) => `  { d: '${s.d}', fill: '${s.fill}' },`).join('\n')}
]
`
writeFileSync(new URL('../src/components/hero-joint-faces.ts', import.meta.url), ts)
